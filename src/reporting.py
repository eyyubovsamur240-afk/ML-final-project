        ["Features after encoding", num(data["n_features"])],
        ["Train / Val / Test", f"{num(data['n_train'])} / {num(data['n_val'])} / {num(data['n_test'])}"],
        ["Tier threshold (train median)", f"{num(data['tier_threshold_train'], 0)} AZN"],
        ["Premium share train / val / test",
         f"{pct(data['premium_share']['train'])} / {pct(data['premium_share']['val'])} / {pct(data['premium_share']['test'])}"],
