def to_jsonable(obj):
    if isinstance(obj, dict):
        return {str(k): to_jsonable(v) for k, v in obj.items() if not str(k).startswith("_")}
    if isinstance(obj, (list, tuple)):
        return [to_jsonable(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return None if np.isnan(obj) else float(obj)
    if isinstance(obj, float) and np.isnan(obj):
        return None
    if isinstance(obj, Path):
        return str(obj)
    return obj


def tex_escape(text) -> str:
    """Escape LaTeX specials and drop characters the T1 Times font cannot print."""
    s = str(text)
    s = unicodedata.normalize("NFKD", s)
    s = "".join(ch for ch in s if ord(ch) < 128 or ch in "–—±²")
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}",
            "<": r"$<$", ">": r"$>$", "–": "--", "—": "---", "±": r"$\pm$", "²": r"$^2$"}
    return "".join(repl.get(ch, ch) for ch in s)


def num(x, d: int = 3) -> str:
    """Number for LaTeX: thousands separated with {,}; NaN -> '--'."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    if isinstance(x, (int, np.integer)) or (isinstance(x, float) and d == 0):
        return f"{int(round(x)):,}".replace(",", "{,}")
    return f"{x:,.{d}f}".replace(",", "{,}")


def pct(x, d: int = 1) -> str:
    return "--" if x is None else f"{100 * x:.{d}f}\\%"


def pm(ms, d: int = 3) -> str:
    return "--" if ms is None else f"{num(ms[0], d)}\\ensuremath{{\\pm}}{num(ms[1], d)}"


def sci(x) -> str:
    """1e-05 -> 10^{-5}; 3e-05 -> 3\\times10^{-5}."""
    m, e = f"{x:.0e}".split("e")
    e = int(e)
    return f"\\ensuremath{{10^{{{e}}}}}" if m == "1" else f"\\ensuremath{{{m}\\times10^{{{e}}}}}"


def _macro_name(name: str) -> str:
    if not re.fullmatch(r"[A-Za-z]+", name):
        raise ValueError(f"LaTeX macro names must be letters only: {name}")
    return name


class TexWriter:
    def __init__(self, out_dir: Path):
        self.out_dir = Path(out_dir)
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.macros: dict[str, str] = {}

    def macro(self, name: str, value: str) -> None:
        self.macros[_macro_name(name)] = value

    def table(self, name: str, body: str) -> None:
        (self.out_dir / f"{name}.tex").write_text(body + "\n", encoding="utf-8")

    def flush(self) -> None:
        lines = ["% AUTO-GENERATED by `python -m src.run_all` -- do not edit by hand."]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.macros.items())]
        (self.out_dir / "macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- paired tests
_METRIC_TEX = {"rmse_log": ("RMSE", "RMSE", False),
               "f1": ("F1", "FOne", True), "roc_auc": ("ROC-AUC", "AUC", True)}


def _paired_macro(task: str, pair: str, metric: str) -> str:
    """("A", "Our tree vs sklearn tree", "rmse_log") -> PairedAOurTreeVsSklearnTreeRMSE."""
    words = re.sub(r"[^A-Za-z ]", " ", pair).split()
    return "Paired" + task + "".join(w[0].upper() + w[1:] for w in words) + _METRIC_TEX[metric][1]


def _signed(x, d: int = 4) -> str:
    x = round(x, d) + 0.0                      # +0.0 turns -0.0 into 0.0
    return ("$+$" if x > 0 else "$-$" if x < 0 else "") + num(abs(x), d)


def _paired_verdict(r: dict) -> str:
    """Which model is really better, or that the test cannot tell them apart."""
    if not r["significant"]:
        return "no real difference"
    first, second = r["pair"].split(" vs ")
    higher = _METRIC_TEX[r["metric"]][2]
    return f"{first if (r['diff'] > 0) == higher else second} better"


def _write_paired(T: "TexWriter", R: dict) -> list[dict]:
    """Table + macros for the paired bootstrap comparisons (final models, then ensembles)."""
    rows = list(R["final"].get("paired", []))
    rows += R.get("bonus", {}).get("ensembles", {}).get("paired", [])
    body, last_task = [], None
    for r in rows:
        if last_task is not None and r["task"] != last_task:
            body.append(["MIDRULE"])
        last_task = r["task"]
        lo, hi = r["ci"]
        body.append([r["task"], tex_escape(r["pair"]), _METRIC_TEX[r["metric"]][0],
                     num(r["a"], 4), num(r["b"], 4),
                     f"{_signed(r['diff'])} [{_signed(lo)}, {_signed(hi)}]",
                     "$<$0.001" if r["p"] < 0.001 else num(r["p"], 3), tex_escape(_paired_verdict(r))])
    T.table("tab_paired", _tabular("@{}cllrrcrl@{}",
            ["Task", "Comparison (first vs second)", "Metric", "First", "Second",
             "Difference [95\\% CI]", "$p$", "Verdict"], body) if body else "(no paired comparisons)")

    # one Diff / CI / Word macro per (pair, metric), "--" when a model was not run
    have = {(r["task"], r["pair"], r["metric"]): r for r in rows}
    n_metrics = {"A": ("rmse_log",), "B": ("f1", "roc_auc")}
    for task, pair, _, _ in config.PAIRED_COMPARISONS + config.ENSEMBLE_PAIRS:
        for metric in n_metrics[task]:
            name = _paired_macro(task, pair, metric)
            r = have.get((task, pair, metric))
            T.macro(name + "Diff", _signed(r["diff"]) if r else "--")
            T.macro(name + "CI", f"[{_signed(r['ci'][0])}, {_signed(r['ci'][1])}]" if r else "--")
            T.macro(name + "Word", ("significant" if r["significant"] else "not significant") if r else "--")
    T.macro("NBoot", num(R["settings"].get("n_boot", config.N_BOOT)))
    T.macro("PairedN", str(len(rows)))
    T.macro("PairedNSig", str(sum(r["significant"] for r in rows)))
    ours_vs_sk = [r for r in rows if "sklearn" in r["pair"] or r["pair"] in
                  ("Pegasos vs LinearSVC", "RFF SVM vs SVC (RBF)")]
    T.macro("PairedNOursVsSk", str(len(ours_vs_sk)))
    T.macro("PairedNOursVsSkSig", str(sum(r["significant"] for r in ours_vs_sk)))
    return rows


# --------------------------------------------------------------------------- verdicts
def _verdicts(T: TexWriter, R: dict) -> None:
    """
    Outcome-dependent WORDS for the prose ("beats" vs "trails"), computed from
    the numbers so the text stays true when the data or settings change.
    """
    fin = R["final"]
    reg, clf = fin["regression"], fin["classification"]
    tree = reg["Ours: decision tree"]["metrics"]["rmse_log"]
    ridge = reg["Ours: ridge (bonus)"]["metrics"]["rmse_log"]
    sk_tree = reg["sklearn DecisionTreeRegressor"]["metrics"]["rmse_log"]
    T.macro("TreeVsRidgeWord", "beats" if tree < ridge else "trails")
    T.macro("TreeVsSkTreeDiff", num(abs(tree - sk_tree), 4))
    ours = {k: v["metrics"]["f1"] for k, v in clf.items() if k.startswith("Ours")}
    best_ours = max(ours, key=ours.get)
    T.macro("BestOurClf", tex_escape(best_ours.replace("Ours: ", "our ")))
    T.macro("BestOurClfFOne", num(ours[best_ours]))
    best_all = max(clf, key=lambda k: clf[k]["metrics"]["f1"])
    T.macro("BestAnyClf", tex_escape(best_all.replace("Ours: ", "our ")))
    T.macro("BestOverallClause", "which is also the best model overall" if best_all == best_ours else
            "while the best model overall is " + tex_escape(best_all.replace("Ours: ", "our ")) +
            f" (F1 {num(clf[best_all]['metrics']['f1'])})")
    lin = clf["Ours: linear SVM (Pegasos)"]["metrics"]["f1"]
    rff = clf["Ours: RBF SVM (RFF + Pegasos)"]["metrics"]["f1"]
    T.macro("RFFMinusLinear", ("+" if rff >= lin else "$-$") + num(abs(rff - lin)))
    T.macro("RFFVsLinearWord", "improves on" if rff > lin + 0.005 else
            ("matches" if abs(rff - lin) <= 0.005 else "falls short of"))
    tclf = clf["Ours: decision tree"]["metrics"]["f1"]
    T.macro("SVMVsTreeWord", "outperforms" if max(lin, rff) > tclf + 0.005 else
            ("matches" if abs(max(lin, rff) - tclf) <= 0.005 else "trails"))
    sk_lin = clf["sklearn LinearSVC"]["metrics"]["f1"]
    tm, sm = clf["Ours: decision tree"]["metrics"], clf["Ours: linear SVM (Pegasos)"]["metrics"]
    if tm["f1"] > sm["f1"] and tm["roc_auc"] < sm["roc_auc"] - 0.02:
        T.macro("AUCContrastSentence",
                f"By ROC-AUC the order flips ({num(tm['roc_auc'])} for the tree against {num(sm['roc_auc'])} for the "
                "SVM): the selected tree grows nearly pure leaves, so its probabilities are almost binary and rank "
                "listings poorly, while SVM margins grade them smoothly.")
    else:
        T.macro("AUCContrastSentence", "")
    T.macro("PegasosVsLiblinearFOneDiff", num(abs(lin - sk_lin), 3))
    cc = R["tree"]["criterion_comparison"]
    g, e = cc["gini"]["val_f1"], cc["entropy"]["val_f1"]
    T.macro("CritWinner", "Gini" if g >= e else "entropy")
    T.macro("CritDiff", num(abs(g - e), 3))
    T.macro("CritSimilarity", "behave almost identically" if abs(g - e) < 0.01 else "differ noticeably")
    lc = R["tree"]["learning_curve"]["reg_va"]
    still = len(lc) > 1 and lc[-1] < lc[-2] - 0.002
    T.macro("LCVerdict", "validation error is still falling at the full training size, so more data "
            "would still help" if still else "validation error has flattened out, so more data of the "
            "same kind would help little")
    conv = R["svm"]["convergence"]["batch_final_objective"]
    k1 = next((v for k, v in conv.items() if k.startswith("batch 1,")), None)
    kb = next((v for k, v in conv.items() if k.startswith("batch") and "last" in k and not k.startswith("batch 1,")), None)
    kf = conv.get("full batch")
    if k1 and kb:
        T.macro("BatchVerdict", "make as much progress per epoch as" if abs(kb - k1) / k1 < 0.05 else
                ("make more progress per epoch than" if kb < k1 else "make somewhat less progress per epoch than"))
    else:
        T.macro("BatchVerdict", "compare with")
    T.macro("FullBatchVerdict", "lags far behind" if (kf and kb and kf > 1.1 * kb) else "ends close to the mini-batch runs")
    rc = R["svm"]["rff_components"]
    D_, auc_, err_ = np.array(rc["D"], float), np.array(rc["val_auc"], float), np.array(rc["kernel_err"], float)
    slope = float(np.polyfit(np.log(D_), np.log(err_), 1)[0]) if len(D_) > 1 else float("nan")
    T.macro("RFFErrSlope", num(slope, 2).replace("-", "$-$"))
    quarter = auc_[D_ <= D_.max() / 4]
    sat = len(quarter) and (auc_.max() - quarter.max()) < 0.005
    T.macro("RFFDVerdict", "saturates well before the largest $D$" if sat else "keeps improving up to the largest $D$")
    grid = R["svm"]["rff_grid"]
    g_vals = sorted({r["gamma"] for r in grid})
    l_vals = sorted({r["lambda_"] for r in grid})
    br = R["svm"]["best_rff"]
    edges = []
    if br["gamma"] == g_vals[0]:
        edges.append("the smallest bandwidth $\\gamma$")
    elif br["gamma"] == g_vals[-1]:
        edges.append("the largest bandwidth $\\gamma$")
    if br["lambda_"] == l_vals[0]:
        edges.append("the weakest regularisation $\\lambda$")
    elif br["lambda_"] == l_vals[-1]:
        edges.append("the strongest regularisation $\\lambda$")
    if edges:
        note = ("Validation picks " + " and ".join(edges) + " in the grid"
                + (": the RBF kernel prefers to be nearly linear on these features, so the extension adds little over the linear SVM."
                   if br["gamma"] == g_vals[0] else ", so the optimum may lie just outside it."))
    else:
        note = "Both selected values lie inside the grid."
    T.macro("RFFGridNote", note)
    dr = R["analysis"]["decile_residuals"]["Our tree"]
    T.macro("TopDecileWord", "under-predicts" if dr[-1] < 0 else "over-predicts")
    T.macro("BottomDecileWord", "over-predicts" if dr[0] > 0 else "under-predicts")
    T.macro("ShrinkageSentence",
            "Leaves average many listings, which pulls the extremes towards the mean; this is the "
            "variance-reduction side of the bias--variance trade-off." if (dr[-1] < 0 < dr[0]) else
            "The errors at the extremes do not follow the usual shrink-to-the-mean pattern, which "
            "points to mislabelled or atypical listings in the tails.")
    groups = R["analysis"]["error_groups"].get("By listings in district (dev)", [])
    if len(groups) >= 2:
        T.macro("SparseDistrictSentence",
                f"The test MAE is {num(groups[0][1])} for listings whose district has "
                f"{tex_escape(groups[0][0])} training examples, against {num(groups[-1][1])} for "
                f"{tex_escape(groups[-1][0])}: rare districts fall into the ``other'' column and fall "
                "back on coordinates.")
    elif groups:
        T.macro("SparseDistrictSentence",
                f"Every test listing's district has {tex_escape(groups[0][0])} training examples, so "
                "district sparsity does not show up in this split.")
    else:
        T.macro("SparseDistrictSentence", "")
    a_ = R["analysis"]["tree_vs_sklearn"]["regression"]
    if a_["root_ours"] and a_["root_sk"] and a_["root_ours"][0] == a_["root_sk"][0] \
            and abs(a_["root_ours"][1] - a_["root_sk"][1]) < 1e-3:
        T.macro("RootSplitSentence", "Both trees choose the same root split ("
                + tex_escape(f"{a_['root_ours'][0]} <= {a_['root_ours'][1]:.3f}") + ").")
    elif a_["root_ours"] and a_["root_sk"] and a_.get("root_same_partition"):
        T.macro("RootSplitSentence", "At the root both trees send the same rows left: ours splits on "
                + tex_escape(f"{a_['root_ours'][0]} <= {a_['root_ours'][1]:.3f}") + ", scikit-learn on the equivalent "
                + tex_escape(f"{a_['root_sk'][0]} <= {a_['root_sk'][1]:.3f}") + " (an exact tie between monotone transforms of the same feature).")
    elif a_["root_ours"] and a_["root_sk"]:
        T.macro("RootSplitSentence", "The root splits are " + tex_escape(f"{a_['root_ours'][0]} <= {a_['root_ours'][1]:.3f}")
                + " (ours) and " + tex_escape(f"{a_['root_sk'][0]} <= {a_['root_sk'][1]:.3f}") + " (scikit-learn).")
    else:
        T.macro("RootSplitSentence", "")
    if "bonus" in R:
        ab = R["bonus"]["unsupervised"]["ablation"]
        T.macro("AblationWord", "lowers" if ab["val_rmse_with_clusters"] < ab["val_rmse_without"] - 1e-4
                else "does not lower")
        e_ = R["bonus"]["ensembles"]
        rf_ = e_["rf_reg"]["ours"]["rmse_log"]
        T.macro("ForestGainPct", pct(1 - rf_ / tree))
        T.macro("BoostGainPct", pct(1 - e_["gb_reg"]["ours"]["rmse_log"] / tree))
        T.macro("ForestVsTreeWord", "lowers" if rf_ < tree else "does not lower")
        T.macro("EnsembleVerdict", "which is why our forest beats the single tree" if rf_ < tree else
                "although on this split our forest does not beat the single tree")
        gbc = R["bonus"]["ensembles"]["curves"]["gb"]
        T.macro("BoostCurveVerdict", "falls steadily" if gbc[-1] <= min(gbc) + 1e-9 else "falls and then flattens")
    else:
        for k in ("AblationWord", "ForestGainPct", "BoostGainPct", "ForestVsTreeWord", "BoostCurveVerdict"):
            T.macro(k, "--")
        T.macro("EnsembleVerdict", "which is why ensembles usually beat a single tree")
    a = R["analysis"]["tree_vs_sklearn"]["regression"]["structure"]
    causes = ["exact gain ties"]
    if a["max_threshold_diff"] > 0 or a.get("float32_divergence", 0):
        causes.append("scikit-learn's float32 cast of the features")
    if a["gain_mismatch"]:
        causes.append(f"{a['gain_mismatch']} unexplained split(s)")
    T.macro("TreeGapCause", " and ".join(causes))


