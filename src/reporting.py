    T.macro("OurTreeRMSE", num(r_t["rmse_log"]))
    T.macro("OurTreeRtwo", num(r_t["r2_log"]))
    T.macro("OurTreeRtwoAZN", num(r_t["r2_azn"]))
    T.macro("OurTreeMAEAZN", num(r_t["mae_azn"], 0))
    T.macro("OurTreeMAPE", pct(r_t["mape"]))
